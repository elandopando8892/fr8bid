export type Copy = (typeof COPY)[Lang];

/** Spanish unless the browser prefers English. */
export function initialLang(): Lang {
  try {
    const saved = window.localStorage.getItem("bidware.request.lang");
    if (saved === "es" || saved === "en") return saved;
  } catch {
    /* storage can be blocked */
  }
  return typeof navigator !== "undefined" && /^en\b/i.test(navigator.language) ? "en" : "es";
}

export function rememberLang(lang: Lang) {
  try {
    window.localStorage.setItem("bidware.request.lang", lang);
  } catch {
    /* storage can be blocked */
  }
}
