/** Only the feed's fixed prefix is translated; route and event data are kept. */
export function movementLabel(label: string) {
  for (const key of ["new", "quote", "closing", "awarded", "expired", "previous"] as const) {
    const prefix = movementCopy[key].es;
    if (label.startsWith(prefix)) return movement(key) + label.slice(prefix.length);
  }
  return label;
}

